const engine=require('../cloudfunctions/orderService/engine');
const crypto=require('node:crypto');
const openid='support-photo-user';
const actor=engine.idFor?engine.idFor(openid):crypto.createHash('sha256').update(openid).digest('hex');
const account={profile:{},loggedOut:false};
const state=engine.initial();
state.members[actor]={marks:[],supportTickets:[]};
const now=Date.parse('2026-11-12T13:00:00+08:00');
assert.throws(()=>engine.execute(state,actor,account,{action:'supportMessage',topic:'order'},now),/message|photo/i);
const photo='cloud://test/order-photos/'+actor+'/'+'a'.repeat(32)+'.jpg';
const sent=engine.execute(state,actor,account,{action:'supportMessage',topic:'payment',photo},now);
assert.equal(sent.ticket.messages.at(-1).photo,photo);
assert.equal(sent.ticket.messages.at(-1).text,'');
assert.equal(sent.ticket.topic,'payment');
const texted=engine.execute(state,actor,account,{action:'supportMessage',text:'Need help with a refund.'},now+1);
assert.equal(texted.ticket.messages.at(-1).text,'Need help with a refund.');
assert.equal(texted.ticket.messages.at(-1).photo,undefined);
console.log('Support chat: no default topic, photo button in composer, and supportMessage accepts a photo or text.');
