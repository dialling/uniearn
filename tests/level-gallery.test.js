const assert=require('node:assert/strict'),fs=require('fs');
global.wx={getStorageSync:()=>null,setStorageSync(){},setNavigationBarTitle(){}};
const store=require('../utils/store');store.reset();store.update(s=>{s.language='zh';s.progression={level:3,points:150};});
let page;global.Page=definition=>{page=definition;};require('../pages/levels/index');
const instance={data:structuredClone(page.data),setData(patch){Object.assign(this.data,patch);}};for(const [key,value] of Object.entries(page))if(typeof value==='function')instance[key]=value;
instance.localize(true);
assert.deepEqual(instance.data.levels.map(x=>x.name),['Yuni 新星','Yuni 帮手','Yuni 达人','Yuni 王牌','Yuni 船长']);
assert.deepEqual(instance.data.levels.map(x=>x.min),[0,20,150,500,1000]);
assert.equal(instance.data.current,2,'gallery opens on the current account level');
assert.equal(instance.data.currentItem.name,'Yuni 达人','the visible card is the current account level');
assert.match(instance.data.levels[1].condition,/首笔订单/);
assert.equal(instance.data.levels[4].benefits[0].detail,'「Yuni 船长」');
assert.equal(instance.data.levels[2].mascot,'/assets/yuni-happy.png');
const xml=fs.readFileSync('pages/levels/index.wxml','utf8'),css=fs.readFileSync('pages/levels/index.wxss','utf8');
assert.doesNotMatch(xml,/class="level-list"/,'the page is not a vertical gallery');
assert.doesNotMatch(xml,/<swiper/,'level content does not slide horizontally');
assert.match(xml,/bindtouchmove="onArcMove"/,'dragging is tracked on the curved level journey');
assert.doesNotMatch(xml,/orbit-slider/,'no circular cursor follows the pointer');
assert.match(xml,/--arc-move:\{\{arcMoveMs\}\}ms/,'the mascot transition duration is adjustable');
assert.match(xml,/class="hero-motion/,'the mascot follows one continuous gesture');
assert.match(css,/cubic-bezier\(\.16,1,\.3,1\)/,'release uses a natural ease-out curve');
assert.match(xml,/class="level-orbit"/,'the five levels use the curved journey layout');
assert.match(xml,/class="orbit-line"/,'the level names follow one visual arc');
assert.match(xml,/hover-class="orbit-press"/,'each level node has a press response');
assert.match(xml,/data-index="\{\{index\}\}" bindtap="select"/,'each level shortcut remains directly clickable');
assert.match(xml,/<text class="orbit-name">\{\{item\.name\}\}<\/text>/,'all five arc nodes show their full level names');
assert.match(xml,/class="mascot-aura power-\{\{currentItem\.level\}\}"/,'each selected level changes the mascot strength treatment');
assert.match(xml,/class="level-mascot power-\{\{currentItem\.level\}\}"/);
assert.match(xml,/currentLevel===currentItem.level/,'current level is marked');
assert.match(xml,/class="benefit-icon"><image src="\{\{item\.icon\}\}"/,'benefit cards use simple graphic icons rather than text glyphs');
assert.doesNotMatch(xml,/detail-check|>✓</,'the four content icons are not font characters');
assert.doesNotMatch(xml,/intro-copy/,'small helper line is removed');
assert.match(xml,/Uniearn 等级成长/,'brand casing follows the product');
assert.match(css,/@keyframes aura-pulse/);
assert.match(css,/@keyframes mascot-float/);
assert.match(css,/@keyframes mascot-power-in/,'switching levels animates the new Yuni into view');
for(const index of [0,1,2,3,4])assert.match(css,new RegExp('\\.orbit-'+index+'\\{'),'all five level names have a place on the arc');
assert.match(css,/\.level-mascot\.power-5\{--power:1\.15\}/,'the highest level has the strongest Yuni treatment');
assert.ok(instance.data.levels.every(level=>level.benefits.every(benefit=>benefit.icon&&benefit.icon.startsWith('/assets/'))),'all four benefit items use program assets');
assert.doesNotMatch(String(page.select),/pageScrollTo/,'level shortcuts switch the visible card without scrolling');
instance.select({currentTarget:{dataset:{index:4}}});
assert.equal(instance.data.current,4);
assert.equal(instance.data.currentItem.name,'Yuni 船长');
instance.setCurrent(0);
instance.orbitRect={left:0,width:400};
instance.onArcStart({changedTouches:[{clientX:300}]});
instance.onArcMove({changedTouches:[{clientX:60}]});
assert.equal(instance.data.current,4,'one uninterrupted gesture can continue across several levels');
assert.equal(instance.data.gestureActive,true,'the gesture remains active until release');
instance.onArcEnd({changedTouches:[{clientX:60}]});
assert.equal(instance.data.gestureActive,false,'release ends the gesture');
assert.equal(instance.data.arcMoveMs,340);
assert.equal(instance.data.arcReleaseMs,420);
instance.onUnload();
assert.ok(!/优惠券|折扣|优先服务|专属功能/.test(JSON.stringify(instance.data.levels)),'gallery must not invent unconfirmed benefits');
console.log('Curved five-level gallery opens on the current level, switches Yuni strength states and uses graphic benefit icons.');
