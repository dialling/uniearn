assert.equal(editor.data.form.area,'wenxing');
assert.equal(editor.data.dormLabels.length,5);
assert.equal(editor.data.form.dorm,'A01');
assert.equal(editor.data.floorLabels.length,6,'A01 has 6 floors');
editor.dorm({detail:{value:4}});
assert.equal(editor.data.form.dorm,'A05');
assert.equal(editor.data.floorLabels.length,20,'A05 has 20 floors');
