const assert=require('node:assert/strict');
const calls=[];
global.wx={getStorageSync:()=>null,setStorageSync(){},showToast(){},
  setNavigationBarColor(o){calls.push(['nav',o.frontColor,o.backgroundColor]);},
  setBackgroundColor(o){calls.push(['bg',o.backgroundColorTop,o.backgroundColorBottom]);}};
const store=require('../utils/store');
store.reset();
const appearance=require('../utils/appearance');
assert.equal(appearance.isDark(),false);
appearance.apply();
assert.deepEqual(calls.at(-2),['nav','#000000','#ffffff'],'light nav bar is white with black text');
assert.deepEqual(calls.at(-1),['bg','#eeede8','#eeede8'],'light window background');
store.update(s=>{s.meAppearance='dark';});
assert.equal(appearance.isDark(),false,'dark appearance is retired');
appearance.apply();
assert.deepEqual(calls.at(-2),['nav','#000000','#ffffff'],'saved dark preference cannot darken the nav bar');
assert.deepEqual(calls.at(-1),['bg','#eeede8','#eeede8'],'saved dark preference cannot darken the window');
let def;global.Component=d=>{def=d;};
require('../components/nav/index.js');
const inst={data:{...def.data},setData(v){Object.assign(this.data,v);},...def.methods};
inst.localize();
assert.equal(inst.data.dark,false,'bottom nav stays light');
assert.equal(inst.data.zh,true);
const page={value:'page-dark',setData(v){this.value=v.darkClass;}};
appearance.apply(page);
assert.equal(page.value,'');
const fs=require('node:fs');
assert.ok(!fs.readFileSync(require.resolve('../pages/profile/index.js'),'utf8').includes('changeAppearance'));
assert.ok(!fs.readFileSync(require.resolve('../pages/profile/index.wxml'),'utf8').includes('me-dark'));
console.log('Appearance: dark theme is retired; chrome, bottom nav and Me stay light.');
