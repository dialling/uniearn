const assert=require('node:assert/strict');
global.wx={getStorageSync:()=>null,setStorageSync(){}};
const {card}=require('../utils/runner-trip-card'),hall=require('../utils/hall-location');
const now=Date.now(),trip={id:'trip',category:'takeout',station:'North gate',dorm:'D02',phase:'collect'};
const first={id:'a',category:'takeout',status:'taken',station:'North gate',dorm:'D02',room:'1111',dormGender:'male',pickupPoint:'文缘夜市门口外卖柜',note:'请勿敲门',dropNote:'At my door',reward:3,small:1,arrived:true,arrivalAt:now,closesAt:now+60000,soup:true};
let result=card(trip,[first],'zh',now);
assert.equal(result.items[0].destination,'文缘 D02 1111室');
assert.equal(result.items[0].origin,'文缘夜市门口外卖柜','the route starts at the locker the customer chose');
assert.equal(result.items[0].gender,'男寝');
assert.equal(result.items[0].pickup,first.pickupPoint);
assert.equal(result.items[0].note,'请勿敲门');
assert.equal(result.items[0].dropNote,'放在门口');
assert.equal(result.items[0].timing,'外卖已到');
assert.equal(result.items[0].status,'待取件');
assert.equal(result.items[0].deadline,'','acceptance deadline is irrelevant after acceptance');
assert.equal(result.items[0].soup,true);
assert.equal(result.total,'3.00');
assert.equal(hall.detail(first,'zh').room,'1111','2026-11-14: hall cards show the room to everyone; phone and pickup codes stay private');
const second={...first,id:'b',status:'collected',dormGender:'female',room:'2222',note:'放前台',small:2,reward:5,pickupPoint:'另一个柜',collectedAt:now};
result=card(trip,[first,second],'zh',now);
assert.equal(result.items.length,2);
assert.deepEqual(result.genders.map(x=>x.key),['male','female']);
assert.equal(result.items[1].destination,'文缘 D02 2222室');
assert.equal(result.items[1].pickup,'另一个柜');
assert.equal(result.items[1].note,'放前台');
assert.equal(result.items[1].status,'配送中');
assert.equal(result.items[1].deadline,require('../utils/workflow').clock(now+900000));
assert.equal(result.quantity,3);
assert.equal(result.total,'8.00');
assert.equal(result.done,false);
const place={...first,destinationType:'place',dorm:'Campus meeting point',room:'',deliveryAddress:'Library front desk',dormGender:'',arrived:false,arrivalAt:now+600000};
result=card(trip,[place],'en',now);
assert.equal(result.items[0].destination,'Library front desk');
assert.equal(result.items[0].gender,'');
assert.match(result.items[0].timing,/^Arrives /);
assert.equal(result.items[0].origin,'Locker at the Wenyuan night market entrance');
const night={...first,night:true,shop:'南门夜市摊位',pickupPoint:'',purchaseStatus:'needs_purchase'};
result=card(trip,[night],'zh',now);
assert.equal(result.type,'夜市代买');
assert.equal(result.items[0].pickup,night.shop);
assert.equal(result.items[0].timing,'未下单 · 需垫付');
const parcel={...first,category:'parcel',fragile:true,deadline:'18:00',parcelItems:[{pickupPoint:'Station A'},{pickupPoint:'Station B'}]};
result=card({...trip,category:'parcel'},[parcel],'zh',now);
assert.equal(result.items[0].pickup,'快递站 A / 快递站 B');
assert.equal(result.items[0].deadline,'18:00');
assert.equal(result.items[0].fragile,true);
const task={...place,category:'task',title:'帮忙搬行李',dueAt:now+600000};
result=card({...trip,category:'task'},[task],'zh',now);
assert.equal(result.items[0].title,'帮忙搬行李');
assert.match(result.items[0].timing,/^完成截止 /);
assert.equal(card(trip,[{...first,status:'delivered'}]).done,false,'awaiting confirmation stays active');
assert.equal(card(trip,[{...first,status:'confirmed'}]).done,true);
assert.equal(card({...trip,phase:'done'},[]).done,true,'empty historical trip remains accessible');
assert.equal(card(trip,[]).items.length,0);
assert.equal(first.note,'请勿敲门','formatting does not mutate the snapshot');
console.log('Runner trip cards: full destinations, per-order notes/pickups, genders, states, deadlines, locales and categories passed');
