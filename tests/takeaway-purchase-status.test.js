const assert=require('node:assert/strict');
const {harness}=require('./helpers/order-cloud');
let definition;const submissions=[];
global.Page=p=>definition=p;
global.wx={getStorageSync:()=>null,setStorageSync(){},showToast(){},redirectTo(){}};
const store=require('../utils/store'),routes=require('../utils/saved-routes'),orders=require('../utils/orders');
const flow=require('../utils/workflow');
function load(name,options={}){
 delete require.cache[require.resolve('../pages/'+name+'/index')];
 require('../pages/'+name+'/index');
 const p={...definition,data:structuredClone(definition.data),setData(x){Object.assign(this.data,x);}};
 if(p.onLoad)p.onLoad(options);return p;
}
const select=value=>({currentTarget:{dataset:{value}}});
(async()=>{
 const h=harness();
 store.reset();store.update(s=>{s.language='zh';s.profile={...s.profile,accountId:h.engine.idFor('customer'),name:'Customer',phone:'13800138000',onboarded:true,campusId:'sip'};});
 routes.save({station:'North gate',name:'My dorm',destinationType:'dorm',dorm:'D01',room:'201',owner:'Customer',phone:'13800138000'});
 orders.upload=async()=>'';
 orders.act=async(action,args)=>{submissions.push(args.data);const result=await h.call('customer',action,args);assert.equal(result.ok,true,result.error);return result.value;};
 const p=load('takeaway',{night:'1'});p.couponManual=true;p.setData({couponId:'',shop:'Night stall'});p.pickLocker({detail:{value:0}});p.totals();
 assert.equal(p.data.purchaseStatus,'ordered');
 const total=p.data.total;
 p.choosePurchaseStatus(select('needs_purchase'));assert.equal(p.data.purchaseStatus,'needs_purchase');
 p.choosePurchaseStatus(select('invalid'));assert.equal(p.data.purchaseStatus,'needs_purchase');
 await p.post();const id=h.state.requests[0].id;
 assert.equal(submissions[0].purchaseStatus,'needs_purchase');
 assert.equal(h.state.requests[0].purchaseStatus,'needs_purchase');
 assert.equal(h.state.requests[0].status,'waiting','purchasing and delivery status are separate');
 assert.equal(h.state.requests[0].reward,Number(total),'upfront status does not add an unspecified meal cost');
 const publicState=(await h.call('stranger','sync')).snapshot;
 assert.equal(publicState.requests.find(r=>r.id===id).purchaseStatus,'needs_purchase');
 assert.equal(publicState.publicJobs.find(r=>r.id===id).purchaseStatus,'needs_purchase','runners see it before acceptance');
 assert.ok(!JSON.stringify(publicState).includes('13800138000'),'recipient phone remains private');
 store.update(s=>{s.requests=publicState.requests;s.publicJobs=publicState.publicJobs;});
 const board=load('jobs');board.refresh();
 assert.equal(board.data.cards[0].needsAdvance,true);
 assert.equal(board.data.cards[0].items[0].purchaseStatus,'needs_purchase');
 assert.ok(!board.data.cards[0].items[0].arrival.includes('Food is there'));
 const accepted=await h.call('runner','accept',{ids:[id]});assert.equal(accepted.ok,true,accepted.error);
 assert.equal(accepted.snapshot.requests.find(r=>r.id===id).purchaseStatus,'needs_purchase');
 assert.match(flow.view(accepted.snapshot.requests.find(r=>r.id===id),'zh').arrivalLabel,/期待送达/);
 const own=(await h.call('customer','sync')).snapshot.requests.find(r=>r.id===id);
 store.update(s=>{s.requests=[own];s.publicJobs=[];});
 assert.equal(load('takeaway',{repeat:id}).data.purchaseStatus,'needs_purchase','repeat orders restore the selection');
 p.choosePurchaseStatus(select('ordered'));await p.post();
 assert.equal(h.state.requests[0].purchaseStatus,'ordered');
 const legacy={...submissions[0]};delete legacy.purchaseStatus;
 const compatible=await h.call('customer','create',{data:legacy});assert.equal(compatible.ok,true,compatible.error);
 assert.equal(h.state.requests.find(r=>r.id===compatible.value.id).purchaseStatus,'ordered','older clients retain their existing behavior');
 for(const value of ['paid',false,{},'']){
  const before=h.state.requests.length;
  const rejected=await h.call('customer','create',{data:{...legacy,purchaseStatus:value}});
  assert.equal(rejected.ok,false);assert.match(rejected.error,/food order status/);
  assert.equal(h.state.requests.length,before);
 }
 p.setNight({currentTarget:{dataset:{night:'1'}}});p.setData({shop:'Night stall'});p.choosePurchaseStatus(select('needs_purchase'));await p.post();
 assert.equal(h.state.requests[0].night,true);assert.equal(h.state.requests[0].purchaseStatus,'needs_purchase');
 const ordinary=load('takeaway');ordinary.couponManual=true;ordinary.setData({couponId:''});ordinary.pickLocker({detail:{value:0}});
 ordinary.choosePurchaseStatus(select('needs_purchase'));assert.equal(ordinary.data.purchaseStatus,'ordered','ordinary takeaway has no purchase status choice');
 ordinary.setData({purchaseStatus:'needs_purchase'});await ordinary.post();
 assert.equal(submissions.at(-1).purchaseStatus,'ordered','stale night-market selections do not mark ordinary takeaway as needing upfront payment');
 const mixed=(await h.call('stranger','sync')).snapshot;
 store.update(s=>{s.requests=mixed.requests;s.publicJobs=mixed.publicJobs;});
 const mixedBoard=load('jobs');mixedBoard.refresh();
 assert.ok(mixedBoard.data.cards.some(c=>c.night&&c.type==='夜市代买'&&c.needsAdvance));
 assert.ok(mixedBoard.data.cards.some(c=>!c.night&&c.type==='外卖代取'&&!c.needsAdvance));
 assert.ok(mixedBoard.data.cards.every(c=>c.rows.every(r=>!!r.night===c.night)),'night-market and ordinary takeaway are never merged together');
 console.log('Food order status: selection, cloud validation/storage, runner visibility, privacy, unchanged fee, legacy clients, repeat and night-market orders passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
