const assert = require('node:assert/strict');
const engine = require('../cloudfunctions/orderService/engine');
const deletion = require('../cloudfunctions/orderService/deletion');
const wallet = require('../cloudfunctions/orderService/wallet');
const rewards = require('../cloudfunctions/orderService/rewards');
const {harness} = require('./helpers/order-cloud');

const now = Date.now();
const actor = engine.idFor('student');
const account = {profile:{universityId:'xjtlu',campusId:'sip',name:'Student',phone:'13800000001'},verification:{status:'verified'},runnerRulesAcceptedAt:1};
let state = engine.initial();
state.requests = []; state.trips = [];
const due = now + 3600000;
const created = engine.execute(state, actor, account, {action:'create', data:{category:'task', title:'Return my books to the library', price:3, dueAt:due, owner:'Student', phone:'13800000001'}}, now);
assert.equal(state.requests[0].closesAt, due, 'a task deadline is also the auto-close time');
const later = now + 3 * 3600000;
engine.execute(state, actor, account, {action:'changeTaskDeadline', id:created.id, dueAt:later}, now + 10);
assert.equal(state.requests[0].dueAt, later);
assert.equal(state.requests[0].closesAt, later, 'moving the deadline moves auto-close with it');
engine.expire(state, due + 1000);
assert.equal(state.requests[0].status, 'waiting', 'the old deadline no longer refunds the task');
assert.throws(() => engine.execute(state, actor, account, {action:'changeTaskDeadline', id:created.id, dueAt:now - 1000}, now + 20), /future deadline/);
assert.throws(() => engine.execute(state, actor, account, {action:'changeTaskDeadline', id:'missing', dueAt:later}, now + 20), /cannot be changed/);
engine.expire(state, later);
assert.equal(state.requests[0].status, 'refunded');

const runner = 'b'.repeat(64);
const ledger = {requests:[], trips:[], members:{[actor]:{marks:[]}, [runner]:{marks:[]}}, receipts:{}, wallets:{[runner]:{balance_cents:-200, transactions:[], withdrawals:[], migrated:true}}, adjustments:[{id:'a1', runnerAccountId:runner, amount:2, note:'Reviewed deduction note', at:1}, {id:'a2', runnerAccountId:actor, amount:1}]};
assert.equal(deletion.purge(ledger, runner, now).counts.wallets, 1);
assert.equal(ledger.wallets[runner], undefined);
assert.deepEqual(ledger.adjustments.map(a => a.id), ['a2']);
wallet.settle(ledger, now + 1);
assert.equal(ledger.wallets[runner], undefined, 'a deleted runner deduction cannot recreate a wallet');

const photo = 'cloud://test/order-photos/' + engine.idFor('runner') + '/' + 'a'.repeat(32) + '.jpg';
const h = harness();
const base = {category:'takeout', owner:'Customer', phone:'13801026092', station:'North gate', dorm:'Dorm 7', room:'412', bags:1, price:4, arrived:true};
(async () => {
  const delivered = (await h.call('customer', 'create', {data:base})).value.id;
  assert.equal((await h.call('runner', 'accept', {ids:[delivered]})).ok, true);
  assert.equal((await h.call('runner', 'pickup', {id:delivered})).ok, true);
  assert.equal((await h.call('runner', 'deliver', {id:delivered, photo, location:'Downstairs'})).ok, true);
  const second = await h.call('customer', 'create', {data:base, couponId:'welcome-free'});
  assert.equal(second.ok, true, second.error);
  const taken = second.value.id;
  assert.equal((await h.call('runner', 'accept', {ids:[taken]})).ok, true);
  const coupon = () => h.state.members[engine.idFor('customer')].coupons.find(c => c.id === 'welcome-free');
  assert.equal(coupon().usedBy, taken);
  const closed = await h.call('customer', 'closeMyOrders');
  assert.equal(closed.ok, true, closed.error);
  assert.equal(h.state.requests.find(r => r.id === delivered).status, 'delivered', 'a delivered order stays payable');
  assert.equal(h.state.requests.find(r => r.id === taken).status, 'cancelled');
  assert.equal(coupon().usedBy, undefined, 'closing the order gives the coupon back');
  const row = h.state.requests.find(r => r.id === delivered);
  const overview = await h.call('runner', 'wallet');
  assert.equal(overview.value.pending_cents, Math.round((row.reward + Number(row.runnerBonus || 0)) * 100));

  const inviteAt = Date.parse('2026-11-05T04:00:00Z');
  const board = {members:{}, requests:[], trips:[], loyaltyStartedAt:1};
  const inviter = 'inviter-account-1', friend = 'friend-account-22';
  rewards.init(board, inviter, inviteAt); rewards.init(board, friend, inviteAt);
  board.requests.push({id:'old', ownerId:friend, status:'confirmed', confirmedAt:inviteAt - 86400000, reward:3, serviceFee:0, createdAt:inviteAt - 86400000});
  rewards.invite(board, friend, inviter.slice(0, 12), inviteAt);
  assert.equal(board.members[inviter].loyalty.points, 10);
  assert.equal(board.members[friend].loyalty.points, 10);
  board.requests.push({id:'next', ownerId:friend, status:'confirmed', confirmedAt:inviteAt + 1000, reward:3, serviceFee:0, createdAt:inviteAt});
  rewards.settle(board, inviteAt + 2000);
  assert.equal(board.members[inviter].coupons.find(c => c.id === 'invite-' + friend).pending, true, 'a classmate who already completed an order does not unlock the first-order coupon');
  console.log('State machine: deadline auto-close, delivered-order close guard, coupon restore, deleted deductions, invite points and first-order coupon passed.');
})().catch(e => { console.error(e); process.exitCode = 1; });
