const assert=require('node:assert/strict');
const {harness}=require('./helpers/order-cloud');
let definition;
global.Page=x=>definition=x;
global.wx={getStorageSync:()=>null,setStorageSync(){},reLaunch(){},navigateTo(){},createSelectorQuery(){return {select(){return this;},boundingClientRect(){return this;},exec(){}};}};
const store=require('../utils/store');
function page(){delete require.cache[require.resolve('../pages/jobs/index')];require('../pages/jobs/index');const p={...definition,data:structuredClone(definition.data)};p.setData=v=>Object.assign(p.data,v);return p;}
(async()=>{
 const h=harness();
 const created=await h.call('customer','create',{data:{category:'takeout',owner:'Student',phone:'13800000001',station:'North gate',dorm:'A05',room:'1111',note:'门口放，电话1111',bags:1,price:4,arrived:true,codes:['AB12']}});
 assert.equal(created.ok,true,created.error);
 const taken=await h.call('runner','accept',{ids:[created.value.id]});
 assert.equal(taken.ok,true,taken.error);
 const stranger=await h.call('stranger','sync');
 const pub=stranger.snapshot.publicJobs.find(r=>r.id===created.value.id);
 assert.ok(pub,'everyone can still see an in-progress hall order');
 assert.equal(pub.status,'taken');
 assert.equal(pub.dorm,'A05');
 assert.equal(pub.room,'1111');
 assert.equal(pub.note,'门口放，电话1111');
 for(const key of ['phone','codes','owner','ownerId','photo','orderPictures'])assert.ok(!(key in pub),'public in-progress jobs omit '+key);
 assert.equal((stranger.snapshot.requests||[]).find(r=>r.id===created.value.id),undefined,'strangers do not receive the private request after acceptance');
 const runner=await h.call('runner','sync');
 const own=runner.snapshot.requests.find(r=>r.id===created.value.id);
 assert.ok(own,'the assigned runner still receives the full order');
 assert.equal(own.room,'1111');
 assert.equal(own.phone,'13800000001');
 assert.ok(own.codes&&own.codes.length,'the assigned runner receives pickup codes');
 store.reset();
 store.update(s=>{s.language='zh';s.profile={...s.profile,accountId:h.engine.idFor('stranger'),campusId:'sip',onboarded:true,studentVerified:true,runnerRulesAccepted:true};s.publicJobs=[pub];s.requests=[];});
 const hall=page();hall.refresh();
 const card=hall.data.cards.find(c=>c.ids&&c.ids.includes(created.value.id));
 assert.ok(card,'in-progress orders stay visible in another student’s hall');
 assert.equal(card.running,true);
 assert.equal(card.myRun,false);
 assert.equal(card.location.room,'1111');
 assert.equal(card.items[0].note,'门口放，电话1111');
 assert.equal(hall.data.takenCount,1);
 hall.completedOrder({currentTarget:{dataset:{ids:[created.value.id]}}});
 assert.ok(hall.data.publicDetail);
 assert.equal(hall.data.publicDetail.statusLabel,'已接单');
 assert.equal(hall.data.publicDetail.canTake,false);
 const shown=JSON.stringify(hall.data.publicDetail);
 assert.ok(!shown.includes('13800000001'));
 assert.ok(!shown.includes('AB12'));
 assert.match(shown,/1111/);
 console.log('Hall in-progress privacy: everyone sees taken hall cards with room and notes; phone and pickup codes stay with the runner.');
})().catch(e=>{console.error(e);process.exitCode=1;});
