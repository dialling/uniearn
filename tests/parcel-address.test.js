const assert=require('node:assert/strict');
let def,navigation;
global.Page=x=>def=x;
global.wx={getStorageSync:()=>null,setStorageSync(){},showToast(){},navigateTo:o=>{navigation=o;if(o.success)o.success({eventChannel:{emit(){}}});}};
const store=require('../utils/store');
const takeawayRoutes=require('../utils/saved-routes');
const parcelRoutes=takeawayRoutes.forService('parcel');
function page(name){
 delete require.cache[require.resolve('../pages/'+name+'/index')];
 require('../pages/'+name+'/index');
 return {...def,data:structuredClone(def.data),setData(v){Object.assign(this.data,v);}};
}
(async()=>{
 store.reset();
 store.update(s=>{s.profile={...s.profile,accountId:'student-a',onboarded:true,name:'Student A',phone:'13800138000',pickup:'North gate'};});
 const food=takeawayRoutes.save({name:'My dorm',station:'North gate',dorm:'Dorm 3',room:'101',owner:'Student A',phone:'13800138000'});
 const parcel=page('create');parcel.loadProfile();
 assert.equal(parcel.data.routeId,food.id,'parcel form uses the takeaway address');
 assert.equal(parcel.data.room,'101');
 parcel.setData({routeId:'',firstAddress:true,dormIndex:0,room:'412',name:'Student A',phone:'13800138000',note:'Leave at the desk',pickupPoint:'Actual parcel station',pickupAddress:'Station address',codes:['1-2-3456']});
 await parcel.saveAddress();
 const shared=parcelRoutes.list().find(x=>x.room==='412');
 assert.ok(shared);
 assert.equal(shared.deliveryNote,'Leave at the desk');
 assert.equal(takeawayRoutes.list().length,2,'both services use one address list');
 assert.equal(parcel.data.pickupPoint,'Actual parcel station');
 assert.deepEqual(parcel.data.codes,['1-2-3456']);
 const takeaway=page('takeaway');takeaway.onLoad();
 takeaway.route({currentTarget:{dataset:{id:shared.id}}});
 assert.equal(takeaway.data.room,'412','takeaway can choose an address saved from parcel posting');
 assert.equal(takeaway.data.station,'North gate','switching delivery addresses does not change the takeaway pickup point');
 parcelRoutes.setDefault(shared.id);
 store.update(s=>{s.profile.pickup='';});
 const noPickup=page('takeaway');noPickup.onLoad();
 assert.equal(noPickup.data.routeId,shared.id);
 assert.equal(noPickup.data.station,'','a parcel address must not become a takeaway pickup point');
 assert.equal(noPickup.data.addressReady,true,'shared delivery addresses work without selecting a takeaway gate');
 store.update(s=>{s.profile.pickup='North gate';});
 parcel.manageAddresses();assert.match(navigation.url,/\/pages\/address\/index\?pick=1/);
 takeaway.manage();assert.match(navigation.url,/\/pages\/address\/index\?pick=1/);
 takeaway.addAddress();assert.match(navigation.url,/\/pages\/address-add\/index/);
 const place=parcelRoutes.save({name:'Library',destinationType:'place',deliveryAddress:'Library front desk',owner:'Roommate',phone:'13900139000'});
 const manager=page('address');manager.setData({zh:true});manager.refresh();
 assert.equal(manager.data.list.length,3);
 assert.equal(manager.data.list.find(x=>x.id===place.id).place,'Library front desk','shared manager includes other delivery places');
 manager.edit({currentTarget:{dataset:{id:place.id}}});assert.match(navigation.url,/\/pages\/address-edit\/index\?id=/);
 parcel.chooseAddress({currentTarget:{dataset:{id:place.id}}});
 assert.equal(parcel.data.deliveryAddress,'Library front desk');
 assert.equal(parcel.data.pickupPoint,'Actual parcel station','changing destination does not change parcel pickup');
 const original=structuredClone(parcelRoutes.list());
 parcel.editAddress();navigation.events.routeApplied({...original.find(x=>x.id===place.id),deliveryAddress:'For this order'});
 assert.equal(parcel.data.deliveryAddress,'For this order');
 assert.deepEqual(parcelRoutes.list(),original,'per-order editing does not overwrite saved addresses');
 parcelRoutes.setDefault(shared.id);
 assert.equal(takeawayRoutes.list().find(x=>x.default).id,shared.id,'default address is shared');
 parcelRoutes.remove(place.id);
 assert.equal(takeawayRoutes.list().some(x=>x.id===place.id),false,'deletion is shared');
 store.update(s=>{s.profile.accountId='student-b';});
 assert.equal(parcelRoutes.list().length,0,'addresses are isolated by account');
 store.update(s=>{s.profile.accountId='student-a';s.parcelRoutes=[{id:'parcelRoute-old',accountId:'student-a',destinationType:'dorm',name:'My dorm',dorm:'Dorm 7',room:'500',owner:'Student A',phone:'13800138000',default:true}];delete s.deliveryAddressesUnified;});
 const migrated=store.get();
 assert.equal(migrated.routes.some(x=>x.id==='parcelRoute-old'),true,'legacy parcel addresses are migrated');
 assert.equal(parcelRoutes.list().some(x=>x.id==='parcelRoute-old'),true);
 assert.equal(takeawayRoutes.list().filter(x=>x.default).length,1,'migration keeps one default per account');
 store.reset();
 const legacy={destinationType:'dorm',name:'My dorm',dorm:'Dorm 6',room:'201',owner:'Student A',phone:'13800138000'};
 store.update(s=>{s.routes=[{...legacy,id:'route-old',default:true}];s.parcelRoutes=[{...legacy,id:'parcelRoute-duplicate',default:true,deliveryNote:'Leave at the desk'}];delete s.deliveryAddressesUnified;});
 assert.equal(store.get().routes.length,1,'matching legacy addresses are combined');
 assert.equal(parcelRoutes.list()[0].deliveryNote,'Leave at the desk');
 store.update(s=>{s.profile.accountId='signed-in-later';});
 assert.equal(parcelRoutes.list().length,1,'old addresses remain available when the account signs in later');
 console.log('Shared delivery addresses: parcel/takeaway selection, common management, independent pickup, account isolation and legacy migration passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
