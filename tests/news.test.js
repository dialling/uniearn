const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const {handleNews}=require('../cloudfunctions/newsService/news');
(async()=>{
  let state={revision:0,items:[]},stamp=1000000;
  const clone=x=>structuredClone(x);
  const repo={newsGet:async()=>clone(state),newsMutate:async change=>{const result=change(clone(state));if(result.ok){state=result.state;const {state:ignored,...r}=result;return r;}return result;},get:async()=>({}),newsLogin:async()=>({ok:true})};
  const invoke=(event,isAdmin=true)=>handleNews({event,isAdmin,repo,id:'admin',now:()=>stamp});
  const item={titleZh:'校园公告',bodyZh:'正文\n第二行',status:'draft'};
  assert.equal((await invoke({action:'newsSave',revision:0,item},false)).code,'FORBIDDEN');
  let r=await invoke({action:'newsSave',revision:0,item});assert(r.ok);const id=r.id;
  assert.equal((await invoke({action:'newsList'},false)).items.length,0,'draft must stay private');
  assert.equal((await invoke({action:'newsSave',id,revision:0,item})).code,'NEWS_CONFLICT');
  assert.equal((await invoke({action:'newsSave',id,revision:1,item:{...item,bodyZh:''}})).code,'INVALID_NEWS');
  assert.equal((await invoke({action:'newsSave',id,revision:1,item:{...item,cover:'javascript:alert(1)'}})).code,'INVALID_NEWS');
  r=await invoke({action:'newsSave',id,revision:1,item:{...item,status:'published'}});assert(r.ok);
  let feed=await invoke({action:'newsList'},false);assert.equal(feed.items[0]._id,id);assert(!('updatedBy' in feed.items[0]));
  stamp+=1000;
  r=await invoke({action:'newsSave',revision:2,item:{titleEn:'Pinned',bodyEn:'English only',status:'published',pinned:true}});assert(r.ok);
  feed=await invoke({action:'newsList'},false);assert.equal(feed.items[0].titleEn,'Pinned');
  assert((await invoke({action:'newsSave',id,revision:3,item})).ok);assert.equal((await invoke({action:'newsList'},false)).items.length,1,'unpublish must remove immediately');
  assert((await invoke({action:'newsDelete',id,revision:4})).ok);assert.equal((await invoke({action:'newsDelete',id,revision:5})).code,'NEWS_MISSING');
  const timers=[],pending=[];let calls=0;
  const cloud={callFunction(){calls++;return new Promise(resolve=>pending.push(resolve));}};
  const ctx={require:()=>({ensureCloud:()=>cloud}),module:{exports:{}},Date,setTimeout:fn=>{timers.push(fn);return timers.length;},clearTimeout:()=>{}};
  vm.runInNewContext(fs.readFileSync(require.resolve('../utils/news'),'utf8'),ctx);
  const seen=[],errors=[];const stop=ctx.module.exports.subscribe(x=>seen.push(x),e=>errors.push(e),false);
  pending.shift()({result:{ok:true,items:[{_id:'x',titleZh:'中文',bodyZh:'正文',publishedAt:stamp}]}});
  await new Promise(resolve=>setImmediate(resolve));assert.equal(seen[0][0].title,'中文','language fallback');assert.equal(timers.length,1);
  timers.shift()();assert.equal(calls,2);stop();pending.shift()({result:{ok:true,items:[]}});
  await new Promise(resolve=>setImmediate(resolve));assert.equal(seen.length,1,'hidden page must ignore late results');assert.equal(timers.length,0,'hidden page must stop scheduling');assert.equal(errors.length,0);
  console.log('News: draft privacy, permissions, publish/unpublish/delete, conflicts, language fallback and subscription cleanup passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
